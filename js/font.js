function rowsToCols(rows) {
  const cols = [0, 0, 0, 0, 0];
  for (let y = 0; y < 7; y++) {
    for (let x = 0; x < 5; x++) {
      if (rows[y][x] === '#') cols[x] |= 1 << y;
    }
  }
  return cols;
}

/** char -> 5 column bytes */
export const GLYPHS = (() => {
  const out = {};
  for (let i = 0; i < 95; i++) {
    const hex = ASCII.substr(i * 10, 10);
    const cols = [];
    for (let c = 0; c < 5; c++) cols.push(parseInt(hex.substr(c * 2, 2), 16));
    out[String.fromCharCode(32 + i)] = cols;
  }
  for (const [ch, rows] of Object.entries(EXTRA)) out[ch] = rowsToCols(rows);
  return out;
})();

export function glyph(ch) {
  return GLYPHS[ch] || GLYPHS['?'];
}

